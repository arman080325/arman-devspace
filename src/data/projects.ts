import type { Difficulty, Project, VerificationStatus } from "@/types/project";

interface SeedEntry {
  number: number;
  title: string;
  slug: string;
  description: string;
  difficulty: Difficulty;
  complexityReviewed?: Difficulty;
  category: string;
  originalRepoUrl: string | null;
  technologies: string[];
  verificationStatus?: VerificationStatus;
  discrepancyNotes?: string;
  learningObjectives: string[];
  existingFeatures: string[];
  missingFeatures: string[];
  recommendedStack: string[];
}

function makeProject(entry: SeedEntry): Project {
  const timestamp = "2026-01-01T00:00:00.000Z";
  return {
    id: `project-${entry.number}`,
    number: entry.number,
    title: entry.title,
    slug: entry.slug,
    description: entry.description,
    difficulty: entry.difficulty,
    complexityReviewed: entry.complexityReviewed ?? entry.difficulty,
    category: entry.category,
    originalRepoUrl: entry.originalRepoUrl,
    verifiedRepoUrl: null,
    discrepancyNotes: entry.discrepancyNotes ?? null,
    technologies: entry.technologies,
    status: "awaiting",
    verificationStatus: entry.verificationStatus ?? "needs-review",
    isPlaceholder: false,
    learningObjectives: entry.learningObjectives,
    existingFeatures: entry.existingFeatures,
    missingFeatures: entry.missingFeatures,
    recommendedStack: entry.recommendedStack,
    createdAt: timestamp,
    updatedAt: timestamp,
  };
}


const ENTRY_BY_NUMBER = new Map<number, SeedEntry>(
  [...DEFINED_ENTRIES.filter((e) => e.number <= 50), ...ADDITIONAL_DEFINED].map((entry) => [
    entry.number,
    entry,
  ]),
);

/**
 * Canonical 100-project collection in strict numerical order (1 through 100).
 * Reserved slots 51-59, 66-74, and 85-93 remain placeholders awaiting source data.
 */
export const projects: Project[] = Array.from({ length: 100 }, (_, index) => {
  const num = index + 1;
  const entry = ENTRY_BY_NUMBER.get(num);
  if (!entry) {
    return makePlaceholder(num);
  }
  return makeProject(entry);
});

export function getCanonicalProjectBySlug(slug: string): Project | undefined {
  return projects.find((project) => project.slug === slug);
}

export function getCanonicalProjectByNumber(number: number): Project | undefined {
  return projects.find((project) => project.number === number);
}

export function getCanonicalProjectById(id: string): Project | undefined {
  return projects.find((project) => project.id === id);
}
